using System.Diagnostics;
using System.Text;
using System.Text.Json;

// Regenerates SpawnDev.Minecraft's protocol tables from the vanilla server's own data reports, so no packet id is
// ever hand-typed. Usage:
//   dotnet run --project tools/DataGen -- <java.exe> <vanilla server jar (the bundler, e.g. Paper's cache/mojang_1.21.5.jar)>
// Writes SpawnDev.Minecraft/Protocol/PacketIds.g.cs.

if (args.Length != 2)
{
    Console.WriteLine("usage: DataGen <java.exe> <vanilla server bundler jar>");
    return 2;
}
var java = args[0];
var jar = args[1];
var repo = FindRepoRoot();
var work = Path.Combine(Path.GetTempPath(), "vertex-datagen-" + Guid.NewGuid().ToString("N")[..8]);
Directory.CreateDirectory(work);
try
{
    var psi = new ProcessStartInfo(java, ["-DbundlerMainClass=net.minecraft.data.Main", "-jar", Path.GetFullPath(jar), "--reports", "--output", Path.Combine(work, "out")])
    {
        WorkingDirectory = work,
        RedirectStandardOutput = true,
        RedirectStandardError = true,
        UseShellExecute = false,
        CreateNoWindow = true,
    };
    using (var p = Process.Start(psi)!)
    {
        var stdout = p.StandardOutput.ReadToEndAsync();
        var stderr = p.StandardError.ReadToEndAsync();
        p.WaitForExit();
        if (p.ExitCode != 0)
        {
            Console.WriteLine(await stdout);
            Console.WriteLine(await stderr);
            Console.WriteLine($"data generator exited {p.ExitCode}");
            return 1;
        }
    }
    var reports = Path.Combine(work, "out", "reports");
    var version = ReadVersion(Path.Combine(work, "out"), jar);
    var packets = WritePacketIds(Path.Combine(reports, "packets.json"), version);
    var target = Path.Combine(repo, "SpawnDev.Minecraft", "Protocol", "PacketIds.g.cs");
    File.WriteAllText(target, packets);
    Console.WriteLine($"wrote {target}");

    var lang = Path.Combine(repo, "SpawnDev.Minecraft", "Data", "en_us.json.br");
    WriteEnglish(jar, version, lang);
    Console.WriteLine($"wrote {lang}");
    return 0;
}
finally
{
    Directory.Delete(work, recursive: true);
}

static string FindRepoRoot()
{
    var dir = AppContext.BaseDirectory;
    while (dir != null && !File.Exists(Path.Combine(dir, "Vertex.slnx"))) dir = Path.GetDirectoryName(dir);
    return dir ?? throw new InvalidOperationException("Vertex.slnx not found above " + AppContext.BaseDirectory);
}

static string ReadVersion(string outDir, string jar)
{
    // The bundler jar names its inner server jar META-INF/versions/<version>/server-<version>.jar.
    using var zip = System.IO.Compression.ZipFile.OpenRead(jar);
    foreach (var e in zip.Entries)
    {
        var parts = e.FullName.Split('/');
        if (parts.Length == 4 && parts[0] == "META-INF" && parts[1] == "versions" && parts[3].StartsWith("server-", StringComparison.Ordinal))
            return parts[2];
    }
    throw new InvalidDataException("no META-INF/versions/<v>/server-<v>.jar in " + jar);
}

static string WritePacketIds(string packetsJson, string version)
{
    using var doc = JsonDocument.Parse(File.ReadAllText(packetsJson));
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>");
    sb.AppendLine($"// Generated by tools/DataGen from the vanilla {version} server's packets.json report. Do not edit.");
    sb.AppendLine("// </auto-generated>");
    sb.AppendLine("namespace SpawnDev.Minecraft.Protocol;");
    sb.AppendLine();
    sb.AppendLine($"/// <summary>Packet ids for Minecraft {version}, straight from the vanilla server's packet report.</summary>");
    sb.AppendLine("public static class PacketIds");
    sb.AppendLine("{");
    foreach (var state in doc.RootElement.EnumerateObject())
    {
        sb.AppendLine($"    public static class {Pascal(state.Name)}");
        sb.AppendLine("    {");
        foreach (var direction in state.Value.EnumerateObject())
        {
            sb.AppendLine($"        public static class {Pascal(direction.Name)}");
            sb.AppendLine("        {");
            foreach (var packet in direction.Value.EnumerateObject().OrderBy(p => p.Value.GetProperty("protocol_id").GetInt32()))
            {
                var name = packet.Name.Split(':')[1];
                sb.AppendLine($"            public const int {Pascal(name)} = 0x{packet.Value.GetProperty("protocol_id").GetInt32():X2};");
            }
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
    }
    sb.AppendLine("}");
    return sb.ToString().ReplaceLineEndings("\r\n");
}

// The vanilla server jar carries the en_us translations (it translates for the console); chat components arrive
// as translate keys, so the library needs them to show readable text.
static void WriteEnglish(string bundlerJar, string version, string target)
{
    using var bundler = System.IO.Compression.ZipFile.OpenRead(bundlerJar);
    var inner = bundler.GetEntry($"META-INF/versions/{version}/server-{version}.jar")
        ?? throw new InvalidDataException("inner server jar missing");
    using var innerStream = new MemoryStream();
    using (var s = inner.Open()) s.CopyTo(innerStream);
    innerStream.Position = 0;
    using var server = new System.IO.Compression.ZipArchive(innerStream);
    var entry = server.GetEntry("assets/minecraft/lang/en_us.json") ?? throw new InvalidDataException("en_us.json missing");
    Directory.CreateDirectory(Path.GetDirectoryName(target)!);
    using var src = entry.Open();
    using var dst = File.Create(target);
    using var brotli = new System.IO.Compression.BrotliStream(dst, System.IO.Compression.CompressionLevel.SmallestSize);
    src.CopyTo(brotli);
}

static string Pascal(string snake) =>
    string.Concat(snake.Split('_', StringSplitOptions.RemoveEmptyEntries).Select(s => char.ToUpperInvariant(s[0]) + s[1..]));
